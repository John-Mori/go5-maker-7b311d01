_CYRILLIC_RE = re.compile(r"[Ѐ-ӿ]")

# 判定から除く領域= コード柵 → インラインコード → URL(この順。柵を先に潰す)。
_MASK_PATTERNS = (
    re.compile(r"```.*?```", re.S),
    re.compile(r"`[^`\n]*`"),
    re.compile(r"https?://\S+"),
)


def _mask_code_spans(s):
    """コード柵/インラインコード/URL の中身を**同じ長さの空白**へ潰した文字列を返す。

    ★長さを保存する理由= detect_* が返す `index` / `context` は**原文基準**でなければ
      監査ログが別の場所を指す=嘘の位置を記録する。潰すが縮めない。
    ★例外は握って原文を返す(fail-safe)。マスクに失敗しても検知は続ける。
    """
    try:
        out = str(s or "")
        for pat in _MASK_PATTERNS:
            out = pat.sub(lambda m: " " * len(m.group(0)), out)
        return out
    except Exception:
        return str(s or "")


