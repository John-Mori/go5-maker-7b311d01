# 简→日 の対応表。★同形(简==日)の組は捨てる= 表の書き間違いが**そのまま誤発火**になるので、
#   読み込みの時点で機械が落とす(人の目視だけを信用しない)。
_SIMPLIFIED_MAP = {}
for _pair in _SIMPLIFIED_PAIRS.split():
    if len(_pair) == 2 and _pair[0] != _pair[1]:
        _SIMPLIFIED_MAP.setdefault(_pair[0], _pair[1])
_SIMPLIFIED_RE = re.compile("[" + "".join(sorted(_SIMPLIFIED_MAP)) + "]")


def detect_simplified(text, span=20):
    """本文に簡体字が含まれていれば {char, jp, codepoint, index, context} を返す(無ければ None)。

    ★**検知するだけ**。呼び出し側は絶対に送信を止めないこと(沈黙が最悪の事故)。
    ★**自動修正は絶対にしない**(实→実 の置換を入れてはいけない)。理由=ハングル(ルールA)と同じで、
      中国語の引用・固有名詞・「实况ではなく実況」のような**字そのものを論じた文**が実在する。
      置換したら記録を壊す。`jp` は**ログの説明用**であって置換用ではない。
    ★正当な引用(全部門共通規律の「実況であって实况ではない」等)でも鳴る。これは誤検出ではなく
      **仕様**(ルールAの「판」と同じ)。送信を止めないので実害は無い。
    ★空文字・None・非文字列でも例外を出さない(呼び出し側の fail-safe と二重の守り)。
    """
    try:
        s = str(text or "")
        m = _SIMPLIFIED_RE.search(s)
        if not m:
            return None
        i = m.start()
        c = m.group(0)
        return {"char": c, "jp": _SIMPLIFIED_MAP.get(c, ""),
                "codepoint": "U+%04X" % ord(c),
                "index": i, "context": s[max(0, i - span):i + 1 + span]}
    except Exception:
        return None          # 検査が落ちても応答は続ける(fail-safe)


