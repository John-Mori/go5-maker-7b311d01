_CYRILLIC_RE = re.compile(r"[Ѐ-ӿ]")

# キリル→**見た目がそっくりな文字**(ログの説明用のみ)。ここに無い字でも検知はする。
_CYRILLIC_LOOKALIKE = {
    "А": "A", "В": "B", "Е": "E", "К": "K", "М": "M",
    "Н": "H", "О": "O", "Р": "P", "С": "C", "Т": "T",
    "У": "Y", "Х": "X", "І": "I", "Ј": "J", "Ѕ": "S",
    "а": "a", "е": "e", "о": "o", "р": "p", "с": "c",
    "у": "y", "х": "x", "і": "i", "ј": "j",
}


def detect_cyrillic(text, span=20):
    """本文にキリル文字が含まれていれば {char, jp, codepoint, index, context} を返す(無ければ None)。

    ★**検知するだけ**。呼び出し側は絶対に送信を止めないこと(沈黙が最悪の事故)。
    ★**自動修正は絶対にしない**。理由=ハングル/簡体字と同じで、正当な引用が実在する
      (この事故を説明する文書は「К」そのものを含む)。置換したら**記録を壊す**。
    ★空文字・None・非文字列でも例外を出さない(呼び出し側の fail-safe と二重の守り)。
    """
    try:
        s = str(text or "")
        m = _CYRILLIC_RE.search(s)
        if not m:
            return None
        i = m.start()
        c = m.group(0)
        return {"char": c, "jp": _CYRILLIC_LOOKALIKE.get(c, ""),
                "codepoint": "U+%04X" % ord(c),
                "index": i, "context": s[max(0, i - span):i + 1 + span]}
    except Exception:
        return None          # 検査が落ちても応答は続ける(fail-safe)
